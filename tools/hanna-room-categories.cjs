'use strict';
// Use the exact live base-bank projection consumed by hanna-room-bank-sync.
// This generator never opens or writes the room-server repository.
const fs = require('node:fs'), path = require('node:path');
const { parseBank, liveBank } = require('./hanna-room-bank-sync.cjs');
const root = path.resolve(__dirname, '..');
function generate() {
  const bank = liveBank(parseBank(fs.readFileSync(path.join(root, 'quest-data/kunuz-bank-3147.js'))));
  const ids = bank.cats.map(c => c[0]);
  return '/* Generated by tools/hanna-room-categories.cjs from the room sync source. */\n' +
    'window.KunuzRoomCategoryIds = Object.freeze(' + JSON.stringify(ids, null, 2) + ');\n';
}
module.exports = { generate };
if (require.main === module) {
  const file = path.join(root, 'quest-theme/room-categories.js'), expected = generate();
  if (process.argv.includes('--check')) require('node:assert/strict').equal(fs.readFileSync(file, 'utf8'), expected);
  else fs.writeFileSync(file, expected);
  console.log('Room category IDs match the live base-bank projection.');
}
