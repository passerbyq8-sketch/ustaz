'use strict';
// Use the exact manifest-backed projection consumed by hanna-room-bank-sync.
// This generator never opens or writes the room-server repository.
const fs = require('node:fs'), path = require('node:path');
const { loadKunuzBank } = require('./kunuz-bank.cjs');
const root = path.resolve(__dirname, '..');
async function generate() {
  const bank = await loadKunuzBank(root);
  const ids = bank.cats.map(c => c.slug);
  return '/* Generated by tools/hanna-room-categories.cjs from the room sync source. */\n' +
    'window.KunuzRoomCategoryIds = Object.freeze(' + JSON.stringify(ids, null, 2) + ');\n';
}
module.exports = { generate };
if (require.main === module) {
  generate().then(expected => {
  const file = path.join(root, 'quest-theme/room-categories.js');
  if (process.argv.includes('--check')) require('node:assert/strict').equal(fs.readFileSync(file, 'utf8'), expected);
  else fs.writeFileSync(file, expected);
  console.log('Room category IDs match the complete live manifest projection.');
  }).catch(error => {console.error(error);process.exitCode=1;});
}
