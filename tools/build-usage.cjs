'use strict';
const fs = require('node:fs');
const path = require('node:path');
const root = path.resolve(__dirname, '..');

function build() {
  const sections = JSON.parse(fs.readFileSync(path.join(root, 'config/usage-sections.json'), 'utf8'));
  const source = fs.readFileSync(path.join(root, 'usage-client.js'), 'utf8').replace(/\r\n?/g, '\n');
  const panel = ['lib/panel-policy.cjs', 'panel-client.js'].map(f => fs.readFileSync(path.join(root, f), 'utf8').replace(/\r\n?/g, '\n')).join('\n');
  return '// GENERATED by tools/build-usage.cjs. Edit usage-client.js or config/usage-sections.json.\n'
    + panel + '\nvar EZIK_USAGE_SECTIONS = Object.freeze(' + JSON.stringify(sections) + ');\n' + source;
}

module.exports = { build };
if (require.main === module) {
  const output = path.join(root, 'usage.js');
  const code = build();
  if (process.argv.includes('--check')) {
    if (!fs.existsSync(output) || fs.readFileSync(output, 'utf8') !== code) {
      console.error('usage.js is stale; run npm run build:usage');
      process.exit(1);
    }
    console.log('usage.js matches its source and section whitelist');
  } else { fs.writeFileSync(output, code); console.log('Built usage.js'); }
}
