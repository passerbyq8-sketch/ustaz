#!/usr/bin/env node
// ITEM 4 OF THE REGISTER (OFFLINE) -- the byte sizes the new mushaf's downloads sheet shows the reader.
//
// The sheet states the size of a juz and of the whole mushaf BEFORE the download starts, and refuses
// to start when the free space is under one and a half times that size. Both numbers are only as
// honest as the table they come from, so the table is MEASURED from the tree, never typed:
//
//   pages[n - 1]     the size of assets/madina-hafs/page-NNN.webp       (n = 1..604)
//   geometry[n - 1]  the size of mushaf-lab/geometry/NNN.json, 0 where no file exists (pages 1 and 2)
//
// Both kinds of file are served byte-for-byte as stored: the scans are binary and every geometry file
// is one line with no line ending, so the size on disk is the size on the wire (before compression).
//
//   node tools/mushaf-lab-offline-sizes.cjs           write mushaf-lab/data/offline-sizes.json
//   node tools/mushaf-lab-offline-sizes.cjs --check   exit 1 when the file differs from the tree
//
// quest-bank-integrity-guard.cjs B17 runs the same measurement on every gate run.
'use strict';
const fs = require('fs');
const path = require('path');

const ROOT = path.join(__dirname, '..');
const OUT = path.join(ROOT, 'mushaf-lab', 'data', 'offline-sizes.json');
const pad3 = (n) => String(n).padStart(3, '0');

function measure(root) {
  const pages = [], geometry = [];
  for (let n = 1; n <= 604; n++) {
    const pg = path.join(root, 'assets', 'madina-hafs', 'page-' + pad3(n) + '.webp');
    const ge = path.join(root, 'mushaf-lab', 'geometry', pad3(n) + '.json');
    if (!fs.existsSync(pg)) throw new Error('missing ' + pg);
    pages.push(fs.statSync(pg).size);
    geometry.push(fs.existsSync(ge) ? fs.statSync(ge).size : 0);
  }
  const sum = (a) => a.reduce((x, y) => x + y, 0);
  return {
    note: 'Generated by tools/mushaf-lab-offline-sizes.cjs from the tree. Do not edit by hand.',
    pages, geometry,
    totals: { pages: sum(pages), pageFiles: pages.length, geometry: sum(geometry), geometryFiles: geometry.filter((x) => x > 0).length },
  };
}
const render = (o) => JSON.stringify(o) + '\n';

if (require.main === module) {
  const want = render(measure(ROOT));
  if (process.argv.includes('--check')) {
    const have = fs.existsSync(OUT) ? fs.readFileSync(OUT, 'utf8') : '';
    if (have !== want) { console.error('mushaf-lab/data/offline-sizes.json is NOT what the tree measures; re-run without --check'); process.exit(1); }
    console.log('mushaf-lab/data/offline-sizes.json matches the tree');
  } else {
    fs.writeFileSync(OUT, want);
    const t = JSON.parse(want).totals;
    console.log('wrote ' + path.relative(ROOT, OUT) + ': ' + t.pageFiles + ' pages ' + t.pages + ' bytes, ' + t.geometryFiles + ' geometry files ' + t.geometry + ' bytes');
  }
}
module.exports = { measure, render };
