// ITEM 110 -- assembles the shipped design stylesheet ez110/ez110.css from:
//   tools/ez110/fontfaces.css   the self-hosted faces (fonts/110, OFL) -- vendor rules, URLs rewritten
//   tools/ez110/tokens.cjs      the ONE source of every identity token (light measured, dark derived)
//   tools/ez110/css/*.css       the hand-written layers, in file-name order
// Deterministic: no clock, no environment. `--check` exits 1 when the committed file differs.
// usage: node tools/ez110/build-css.cjs [--check]
'use strict';
const fs = require('fs'), path = require('path');
const { ID, VT } = require('./tokens.cjs');
const ROOT = path.join(__dirname, '..', '..');
const OUT = path.join(ROOT, 'ez110', 'ez110.css');
const FALLBACK = "'IBM Plex Sans Arabic', 'Noto Naskh Arabic', system-ui, sans-serif";
const stack = (f) => (f === "'IBM Plex Sans Arabic'" ? FALLBACK : `${f}, ${FALLBACK}`);
function block(id, mode) {
  const T = ID[id][mode]; const F = ID[id].fonts; const L = [];
  for (const [k, v] of Object.entries(VT)) if (T[k] !== undefined) L.push(`--vt-${v}:${T[k]};`);
  if (mode === 'light') L.push('--vt-radius:18px;', '--vt-radius-sig:24px;', `--vt-font:${stack(F.ui)};`, `--ez110-font-ui:${stack(F.ui)};`, `--ez110-font-head:${stack(F.head)};`);
  for (const [k, v] of Object.entries(T)) { if (VT[k] && k !== 'shadow') continue; L.push(`--ez110-${k.replace(/[A-Z]/g, (m) => '-' + m.toLowerCase())}:${v};`); }
  const sel = mode === 'light' ? `html:root[data-ez110="${id}"]` : `html:root[data-theme="dark"][data-ez110="${id}"]`;
  return `${sel}{${L.join('')}}`;
}
const head = `/* ITEM 110 -- THE DESIGN STYLESHEET. GENERATED by tools/ez110/build-css.cjs -- edit the sources
   (tools/ez110/tokens.cjs, tools/ez110/css/*.css), never this file.
   Loaded by app.js ONLY when one of the identity parts b c d e is lit for this reader; with the
   switch dark it is never requested. Every rule is scoped to html[data-ez110], which only the lit
   path writes. Governing document: DESIGN-SYSTEM.md (item 110 session). */\n`;
const parts = [head, '/* ---- faces: fonts/110, SIL OFL 1.1 (fonts/FONTS-NOTICE.md) ---- */\n', fs.readFileSync(path.join(__dirname, 'fontfaces.css'), 'utf8'),
  '\n/* ---- identity tokens: --vt-* (read by the S100 role map) and --ez110-* ---- */\n'];
for (const id of Object.keys(ID)) { parts.push(block(id, 'light') + '\n'); parts.push(block(id, 'dark') + '\n'); }
const dir = path.join(__dirname, 'css');
for (const f of fs.readdirSync(dir).filter((x) => x.endsWith('.css')).sort()) parts.push(`\n/* ==== ${f} ==== */\n` + fs.readFileSync(path.join(dir, f), 'utf8'));
const css = parts.join('').replace(/\r\n/g, '\n');
if (process.argv.includes('--check')) {
  const cur = fs.existsSync(OUT) ? fs.readFileSync(OUT, 'utf8') : '';
  if (cur !== css) { console.log('ez110.css is STALE -- run node tools/ez110/build-css.cjs'); process.exit(1); }
  console.log('ez110.css up to date (' + Buffer.byteLength(css) + ' bytes)'); process.exit(0);
}
fs.mkdirSync(path.dirname(OUT), { recursive: true });
fs.writeFileSync(OUT, css);
console.log('wrote ez110/ez110.css ' + Buffer.byteLength(css) + ' bytes');
