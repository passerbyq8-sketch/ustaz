// ITEM 110 -- assembles the shipped design stylesheet ez110/ez110.css from:
//   tools/ez110/fontfaces.css   the self-hosted faces (fonts/110, OFL) -- vendor rules, URLs rewritten
//   tools/ez110/tokens.cjs      the ONE source of every identity token (light measured, dark derived)
//   tools/ez110/css/*.css       the hand-written layers, in file-name order
// Deterministic: no clock, no environment. `--check` exits 1 when the committed file differs.
// usage: node tools/ez110/build-css.cjs [--check]
'use strict';
const fs = require('fs'), path = require('path');
const { ID, VT } = require('./tokens.cjs');
const ROOT = path.join(__dirname, '..', '..');
const OUT = path.join(ROOT, 'ez110', 'ez110.css');
const FALLBACK = "'IBM Plex Sans Arabic', 'Noto Naskh Arabic', system-ui, sans-serif";
const stack = (f) => (f === "'IBM Plex Sans Arabic'" ? FALLBACK : `${f}, ${FALLBACK}`);
// ROUND 2 §7-2: the Arabic and Persian digits come from «Ezik Digits» (Readex Pro's own Arabic file, fonts/110, SIL OFL
// 1.1, restricted by unicode-range to U+0660-0669 and U+06F0-06F9), whose zero is a round dot: IBM Plex's zero is drawn
// as a short dash at the interface's small sizes and was read as a minus. Every other character keeps its identity
// face. The plain stack (no digits face) is kept for what must not take it: the answer sheet, where verses and
// hadith are quoted (verses elsewhere already use Amiri by name).
const DIGITS = "'Ezik Digits'";
const withDigits = (st) => `${DIGITS}, ${st}`;
function block(id, mode) {
  const T = ID[id][mode]; const F = ID[id].fonts; const L = [];
  for (const [k, v] of Object.entries(VT)) if (T[k] !== undefined) L.push(`--vt-${v}:${T[k]};`);
  if (mode === 'light') L.push('--vt-radius:18px;', '--vt-radius-sig:24px;', `--vt-font:${withDigits(stack(F.ui))};`, `--ez110-font-ui:${withDigits(stack(F.ui))};`, `--ez110-font-head:${withDigits(stack(F.head))};`, `--ez110-font-plain:${stack(F.ui)};`);
  for (const [k, v] of Object.entries(T)) { if (VT[k] && k !== 'shadow') continue; L.push(`--ez110-${k.replace(/[A-Z]/g, (m) => '-' + m.toLowerCase())}:${v};`); }
  const sel = mode === 'light' ? `html:root[data-ez110="${id}"]` : `html:root[data-theme="dark"][data-ez110="${id}"]`;
  return `${sel}{${L.join('')}}`;
}
const head = `/* ITEM 110 -- THE DESIGN STYLESHEET. GENERATED by tools/ez110/build-css.cjs -- edit the sources
   (tools/ez110/tokens.cjs, tools/ez110/css/*.css), never this file.
   Loaded by app.js ONLY when one of the identity parts b c d e is lit for this reader; with the
   switch dark it is never requested. Every rule is scoped to html[data-ez110], which only the lit
   path writes. Governing document: DESIGN-SYSTEM.md (item 110 session). */\n`;
const DIGITS_FACE = `/* digits only (ROUND 2 §7-2): Readex Pro's Arabic file, variable; its zero is a dot (ink width/height 1.00-1.06,
   measured) and its other digits are the common forms. Sized to Plex's digits (ink height 68-70 against 63 at 100px,
   measured: 91%). El Messiri was tried first and refused: its 7 and 8 are decorative, and its 8 reads as 5 at 13px. */
@font-face {
  font-family: 'Ezik Digits';
  font-style: normal;
  font-weight: 400 700;
  font-display: swap;
  src: url(/fonts/110/SLXYc1bJ7HE5YDoGPuzj_dh8uc7wUy8ZQQyX2Iw1ZEzMhQ.woff2) format('woff2');
  unicode-range: U+0660-0669, U+06F0-06F9;
  size-adjust: 91%;
}
`;
const parts = [head, '/* ---- faces: fonts/110, SIL OFL 1.1 (fonts/FONTS-NOTICE.md) ---- */\n', fs.readFileSync(path.join(__dirname, 'fontfaces.css'), 'utf8'), DIGITS_FACE,
  '\n/* ---- identity tokens: --vt-* (read by the S100 role map) and --ez110-* ---- */\n'];
for (const id of Object.keys(ID)) { parts.push(block(id, 'light') + '\n'); parts.push(block(id, 'dark') + '\n'); }
// the identity picker's miniatures: each one painted in ITS identity's tokens, whatever is lit
parts.push('\n/* ---- picker previews ---- */\n');
for (const id of Object.keys(ID)) for (const mode of ['light', 'dark']) {
  const T = ID[id][mode];
  const sel = (mode === 'light' ? 'html[data-ez110]' : 'html[data-theme="dark"][data-ez110]') + ` .ez110-pv[data-pv="${id}"]`;
  parts.push(`${sel}{--pv-page:${T.page};--pv-surface:${T.surface};--pv-accent:${T.accent};--pv-soft:${T.soft};--pv-line:${T.line};--pv-grad:${T.gradPrayer};--pv-ia:${T.iconA};--pv-ib:${T.iconB};--pv-ink:${T.ink};}\n`);
}
const dir = path.join(__dirname, 'css');
for (const f of fs.readdirSync(dir).filter((x) => x.endsWith('.css')).sort()) parts.push(`\n/* ==== ${f} ==== */\n` + fs.readFileSync(path.join(dir, f), 'utf8'));
const css = parts.join('').replace(/\r\n/g, '\n');
if (process.argv.includes('--check')) {
  const cur = fs.existsSync(OUT) ? fs.readFileSync(OUT, 'utf8') : '';
  if (cur !== css) { console.log('ez110.css is STALE -- run node tools/ez110/build-css.cjs'); process.exit(1); }
  console.log('ez110.css up to date (' + Buffer.byteLength(css) + ' bytes)'); process.exit(0);
}
fs.mkdirSync(path.dirname(OUT), { recursive: true });
fs.writeFileSync(OUT, css);
console.log('wrote ez110/ez110.css ' + Buffer.byteLength(css) + ' bytes');
