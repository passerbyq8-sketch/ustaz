// tools/gen-lib-sections.mjs -- regenerates lib/data/lib-sections.js from the same book-class census
// tools/gen-lib-catalog.mjs reads. PROGRAM ORDER 2026-09-24, م٥: «المكتبة» browses books by their SECTIONS.
//
// WHY A SECOND FILE AND NOT A SEVENTH COLUMN. lib/data/lib-catalog.js rows are pinned at six fields
// (guards/lib-quote-guard.cjs A8), and the quote path reads them by position. The section of each book is
// written here instead, as an array ALIGNED WITH THE CATALOGUE'S ROW ORDER (sorted by id): entry i is the
// section of LIB_CATALOG[i]. A guard asserts the two agree.
//
// THE SECTIONS. The census carries the Shamela folder name, «NNـ (NNN) التفاسير» and its «-مرقم آليا» twin.
// The numbering prefix and the counts inside it are the folder's, and 34 of those counts are wrong
// (program-2026-09-24/05-library/measure/C-catalog.md); so both are dropped, and a numbered folder and its
// auto-numbered twin are one section. The order is the folder number's. 71 folders → 38 sections.
//
// Usage: node tools/gen-lib-sections.mjs [path/to/book-classes.json] [out/path.js]
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const HERE = path.dirname(fileURLToPath(import.meta.url));
const SRC = process.argv[2]
  || 'C:/Users/passe/projects/ustaz-archive/sessions/sources-2026-09-24/00-src/book-classes.json';
const OUT = process.argv[3] || path.join(HERE, '..', 'lib', 'data', 'lib-sections.js');

const census = JSON.parse(fs.readFileSync(SRC, 'utf8'));
const books = (Array.isArray(census.books) ? census.books : []).slice()
  .sort((a, b) => (a.id < b.id ? -1 : a.id > b.id ? 1 : 0));
if (!books.length) throw new Error('no books in ' + SRC);

const folderOf = (category) => {
  const raw = String(category || '').trim();
  const m = /^(\d+)ـ\s*\(\d+\)\s*(.+)$/u.exec(raw);
  const order = m ? Number(m[1]) : 9999;
  const name = (m ? m[2] : raw).replace(/-\s*مرقم آليا\s*$/u, '').trim() || 'أخرى';
  return { order, name };
};

const firstOrder = new Map();
for (const b of books) {
  const { order, name } = folderOf(b.category);
  if (!firstOrder.has(name) || order < firstOrder.get(name)) firstOrder.set(name, order);
}
const sections = [...firstOrder.entries()].sort((a, b) => a[1] - b[1] || (a[0] < b[0] ? -1 : 1)).map(([name]) => name);
const index = new Map(sections.map((name, i) => [name, i]));
const of = books.map((b) => index.get(folderOf(b.category).name));

const lines = [
  '// lib/data/lib-sections.js -- GENERATED by tools/gen-lib-sections.mjs; do not edit by hand.',
  '// Source: ' + path.basename(SRC) + ' (sources round 2026-09-24, 00-src/); ' + books.length + ' books, ' + sections.length + ' sections.',
  '// LIB_SECTION_OF[i] is the section of LIB_CATALOG[i] (both sorted by id); LIB_SECTIONS holds the names in',
  '// the Shamela folder order, a numbered folder and its auto-numbered twin being one section.',
  'export const LIB_SECTIONS = Object.freeze(' + JSON.stringify(sections) + ');',
  'export const LIB_SECTION_SPAN = Object.freeze(' + JSON.stringify([books[0].id, books[books.length - 1].id, books.length]) + ');',
  'export const LIB_SECTION_OF = Object.freeze(' + JSON.stringify(of) + ');',
  '',
];
fs.writeFileSync(OUT, lines.join('\n'));
console.log('wrote', OUT, books.length, 'books', sections.length, 'sections', fs.statSync(OUT).size, 'bytes');
