// Build-only geometry. No source properties or upstream identifiers ship.
import fs from 'node:fs/promises';
import os from 'node:os';
import path from 'node:path';
import {fileURLToPath} from 'node:url';
import {gzipSync} from 'node:zlib';
import {createHash} from 'node:crypto';
import clip from 'polygon-clipping';

const root=path.resolve(path.dirname(fileURLToPath(import.meta.url)),'..');
const cache=path.join(os.tmpdir(),'kunuz-natural-earth-v5.1.2');
await fs.mkdir(cache,{recursive:true});
const source='https://raw.githubusercontent.com/nvkelso/natural-earth-vector/v5.1.2/geojson/';
async function get(name){
  const dest=path.join(cache,name+'.geojson');
  try{return JSON.parse(await fs.readFile(dest,'utf8'))}catch{}
  const r=await fetch(source+name+'.geojson');
  if(!r.ok)throw Error(name+': HTTP '+r.status);
  const body=await r.text();await fs.writeFile(dest,body);return JSON.parse(body);
}
const [low,high,disputes]=await Promise.all([
  get('ne_110m_admin_0_countries'),get('ne_50m_admin_0_countries'),get('ne_10m_admin_0_disputed_areas')
]);
const multi=f=>f.geometry.type==='Polygon'?[f.geometry.coordinates]:f.geometry.coordinates;
const neutralNames=new Set(['Western Sahara','Taiwan','Kosovo','Northern Cyprus','Somaliland','Siachen Glacier']);
const fine=new Set(['Bahrain','Qatar','Lebanon','Malta','Singapore','Kuwait','Luxembourg','Brunei','Cyprus','Palestine','Israel']);
const lowBy=new Map(low.features.map(f=>[f.properties.ADMIN,f]));
const features=new Map(lowBy);
for(const f of high.features)if(fine.has(f.properties.ADMIN)||!features.has(f.properties.ADMIN))features.set(f.properties.ADMIN,f);
const merged=clip.union(multi(features.get('Palestine')),multi(features.get('Israel')));
features.delete('Israel');features.delete('Palestine');
features.set('Palestine',{properties:{ADMIN:'Palestine'},geometry:{type:'MultiPolygon',coordinates:merged}});

// Remove every upstream disputed-area feature from country targets. Regions that
// are separate country features are also anonymous. No guessed bounding boxes.
// The order explicitly treats the complete merged Palestine as one target.
// Do not paint overlapping upstream claim polygons over that merged outline.
const eligibleDisputes=disputes.features.filter(f=>!clip.intersection(multi(f),merged).length);
const rawNeutral=[...eligibleDisputes.map(multi)];
for(const [name,f] of features)if(neutralNames.has(name)){rawNeutral.push(multi(f));features.delete(name)}
const bbox=m=>{
  let b=[Infinity,Infinity,-Infinity,-Infinity];
  for(const p of m)for(const r of p)for(const [x,y] of r){b[0]=Math.min(b[0],x);b[1]=Math.min(b[1],y);b[2]=Math.max(b[2],x);b[3]=Math.max(b[3],y)}return b;
};
const overlap=(a,b)=>a[0]<=b[2]&&a[2]>=b[0]&&a[1]<=b[3]&&a[3]>=b[1];
const cuts=rawNeutral.filter(m=>m.length).map(m=>({m,b:bbox(m)}));
const geom=[];
for(const [name,f] of [...features].sort((a,b)=>a[0].localeCompare(b[0],'en'))){
  let m=multi(f),b=bbox(m);
  for(const n of cuts)if(name!=='Palestine'&&overlap(b,n.b))m=clip.difference(m,n.m);
  if(m.length)geom.push({name,m,b:bbox(m)});
}
// Quantize coordinates to hundredths of a degree; remove collinear intermediates.
// Keep all rings (including holes) and use evenodd in the renderer.
function ringPath(r){
  let pts=r.map(([x,y])=>[Math.round((x+180)*100)/10,Math.round((90-y)*100)/10]);
  pts=pts.filter((p,i)=>!i||p[0]!==pts[i-1][0]||p[1]!==pts[i-1][1]);
  if(pts.length<4)return '';
  pts=pts.filter((p,i,a)=>{if(i===0||i===a.length-1)return true;let p0=a[i-1],p1=a[i+1];return Math.abs((p[0]-p0[0])*(p1[1]-p[1])-(p[1]-p0[1])*(p1[0]-p[0]))>.001});
  if(pts.length<4)return '';
  return pts.map((p,i)=>(i?'L':'M')+p.join(',')).join('')+'Z';
}
const paths=m=>m.map(p=>p.map(ringPath).join('')).join('');
const views={mena:[-18,8,62,44],europe:[-26,34,46,73],asia:[25,-12,180,80],africa:[-20,-36,56,38],americas:[-180,-58,-25,84],world:[-180,-60,180,85]};
const countries=geom.map(({name,m,b})=>[name,paths(m),b.map(n=>Math.round(n*100)/100)]).filter(x=>x[1]);
const neutral=cuts.map(x=>paths(x.m)).filter(Boolean);
const index={views,names:Object.fromEntries(countries.map(c=>[c[0],c[2]]))};
const out='/* Made with Natural Earth (public domain). Generated by tools/build-geo.mjs. */\nvar KUNUZ_GEO='+JSON.stringify({views,countries,neutral})+';\n';
const ix='/* Canonical map targets only; no geometry. Generated by tools/build-geo.mjs. */\nvar KUNUZ_GEO_INDEX='+JSON.stringify(index)+';\n';
if(gzipSync(out).length>=400*1024)throw Error('Geography exceeds compressed budget');
if(/israel|isra[eë]l|\bISR\b|\bIS1\b|إسرائيل|اسرائيل/i.test(out+ix))throw Error('Forbidden source label survived');
await fs.writeFile(path.join(root,'quest-data/kunuz-geo.js'),out);
await fs.writeFile(path.join(root,'quest-data/kunuz-geo-index.js'),ix);
// Metadata is build-only; used by the regression gate to check the union and cuts.
const area=m=>m.reduce((sum,p)=>sum+p.reduce((s,r,i)=>{let a=0;for(let j=1;j<r.length;j++)a+=r[j-1][0]*r[j][1]-r[j][0]*r[j-1][1];return s+(i?-1:1)*Math.abs(a/2)},0),0);
const pal=geom.find(x=>x.name==='Palestine');
const meta={version:'5.1.2',countries:countries.length,neutralFeatures:neutral.length,bytes:Buffer.byteLength(out),gzip:gzipSync(out).length,sha256:createHash('sha256').update(out).digest('hex'),palestine:{polygons:merged.length,sourceArea:area(merged),targetArea:area(pal.m)},disputedNames:[...neutralNames],cutFeatures:eligibleDisputes.map(f=>f.properties.NAME||f.properties.name||f.properties.ADMIN),smallCountries:[...fine].filter(n=>n!=='Israel'),source};
await fs.writeFile(path.join(root,'tools/kunuz-geo-build.json'),JSON.stringify(meta,null,2)+'\n');
console.log(JSON.stringify(meta,null,2));
