
"""Generate school tags from the read-only library index. Authors are in lib-catalog.js."""
import json
from pathlib import Path
import sqlite3
import sys

ROOT = Path(__file__).resolve().parents[1]
DATABASE = Path(sys.argv[1]).resolve()
OUTPUT = ROOT / "lib/data/madhhab-catalog.js"
# Resolve category strings through identified books rather than matching parts of titles.
ANCHORS = {"hanafi": "FC-003532", "maliki": "FC-003623", "shafii": "FC-003660", "hanbali": "FC-003727"}
excluded = set(json.loads((ROOT / "lib/data/removed-sources.json").read_text(encoding="utf8"))["books"])
with sqlite3.connect(DATABASE.as_uri() + "?mode=ro", uri=True) as db:
    tags = {}
    for school, anchor in ANCHORS.items():
        category, = db.execute("select category from books where subject_id=?", (anchor,)).fetchone()
        if not category:
            raise ValueError("Missing category for " + anchor)
        for book_id, in db.execute("select subject_id from books where category=? order by subject_id", (category,)):
            if book_id in excluded:
                continue
            if book_id in tags:
                raise ValueError("Ambiguous catalogue category for " + book_id)
            tags[book_id] = school
lines = ["// Generated by tools/gen-madhhab-catalog.py from the library's four fiqh categories.",
         "export const CATALOG_SCHOOL = Object.freeze({"]
lines.extend(f"  '{book_id}': '{school}'," for book_id, school in sorted(tags.items()))
OUTPUT.write_bytes(("\n".join(lines) + "\n});\n").encode("utf8"))
