// lib/lib-quote.js -- LIB_QUOTE_V1: «انقل لي من كتاب …», answered with the book's own words.
//
// THE OWNER'S ASK (sources order, 24 September 2026). A reader who asks for the TEXT of a book --
// «ما نصّ كلام ابن قدامة في المغني عن المسح على الجوربين»، «انقل لي من كتاب زاد المعاد ما جاء في
// صلاة الضحى» -- is asking for a quotation, and a model's paraphrase of a quotation is exactly the
// thing that must never be presented as one. So the reply is composed HERE, by the server, from
// the library atom itself: a card line naming the book, its author and its place, then the atom's
// text letter for letter as a blockquote. No model call.
//
// WHAT THIS MODULE IS. Pure: it reads no environment and opens no socket. The library call is made
// through the `runTool` it is HANDED (lib/free-brain/tools.js -> runLibrary, the only door
// guards/lib-book-contract-guard.cjs row A7 allows), with the two library switches api/ask.js read.
// Book titles and authors are resolved OFFLINE against lib/data/lib-catalog.js (7,400 books,
// generated by tools/gen-lib-catalog.mjs) -- the service has no catalogue door, and its author door
// "corrects" names into other people (measured: القرضاوي -> القرعاوي), so it is never used here.
//
// WHAT IT CANNOT DO, AND SAYS SO. The service has no page door (only /search; decision D7 of the
// sources round), so «نص صفحة ٥٠ من الجزء ٢٥ من كتاب …» is answered honestly: no page by number,
// here is the road that works (name the topic). No page number is ever invented, and no reply
// names the machinery («المكتبة»، «الفهرس»، «الشاملة» …).
//
// WHY IT HAS ITS OWN WRITER. The finalizer and the takhrij seal were built for MODEL prose. On a
// real atom of عمدة القاري they read «روى ابن أبي شيبة …» inside the book's own text as an
// unsupported attribution and replaced the whole quotation with the refusal sentence (measured,
// 02-build/c3/finalizer-why.mjs). A quotation is not a draft to be repaired: it is either the
// book's text or it is not sent. `writeQuoteReply` writes the same two frames sendSynthesizedText
// writes, without that pass.
